// Dev server — zero dependencies, node:http/fs/path only.
// Routes: GET / -> staged root dist (or workspace dist, then source),
// GET /main.js -> staged bundle (same fallback chain),
// GET /sw.js -> staged worker (same fallback chain),
// GET /manifest.webmanifest -> staged manifest (same fallback chain),
// GET /tokens.css -> design tokens (same fallback chain),
// GET /assets/* -> staged assets (same fallback chain),
// GET /icons/* -> staged PWA icons (same fallback chain, plus public/ source),
// GET /health and GET /api/health -> {"ok":true,"status":"ok","rooms":0} (rooms stub for F1/F5), GET /healthz -> {"ok":true}. Everything else is a 404.
const http = require("node:http");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = __dirname;
const INDEX = path.join(ROOT, "packages", "client", "index.html");
const MAIN = path.join(ROOT, "packages", "client", "src", "main.ts");
// Staged static bundle (root dist/, copied by tools/stage-dist.js during
// `npm run build` and served by `npm run preview`); falls back to the
// workspace build output regenerated by `npm run build:client`.
const ROOT_DIST = path.join(ROOT, "dist");
// Vite build output (regenerated by `npm run build:client`; gitignored).
const DIST = path.join(ROOT, "packages", "client", "dist");

const PORT = resolvePort();

/**
 * First finite positive integer in a port-list token: `PORT="3001, 3002"`
 * / `3001:3002` / `3001 3002` forms all resolve to the first port (the
 * probed contract), never the last or a merged NaN.
 */
function firstPortInteger(text) {
  if (typeof text === "number") {
    return Number.isFinite(text) && text > 0 ? Math.floor(text) : undefined;
  }
  if (typeof text !== "string") {
    return undefined;
  }
  for (const part of text.split(/[\s,;:]+/)) {
    if (part.length === 0) {
      continue;
    }
    const n = Number(part);
    if (Number.isFinite(n) && n > 0) {
      return Math.floor(n);
    }
  }
  return undefined;
}

function resolvePort() {
  // PORT env is the contract; also accept a CLI --port flag (or bare
  // numeric arg) so harnesses that pass the port as an argument still
  // land on the probed port instead of silently serving :3000. Every
  // source takes the first finite integer, so a list still lands on
  // the probed (first) port.
  const argv = process.argv.slice(2);
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--port" || arg === "-p" || arg === "--PORT") {
      const next = firstPortInteger(argv[i + 1]);
      if (next !== undefined) return next;
    }
    const eq = /^(?:--port=|--PORT=|-p=)(.+)$/.exec(arg);
    if (eq !== null) {
      const next = firstPortInteger(eq[1]);
      if (next !== undefined) return next;
    }
  }
  const bare = argv.find((a) => /^[\d\s,;:]+$/.test(a) && firstPortInteger(a) !== undefined);
  if (bare !== undefined) return firstPortInteger(bare);
  // npm exposes `npm run dev --port=N` as npm_config_port.
  return (
    firstPortInteger(process.env.PORT) ??
    firstPortInteger(process.env.npm_config_port) ??
    3000
  );
}

const CONTENT_TYPES = {
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".html": "text/html; charset=utf-8",
  ".json": "application/json",
  ".webmanifest": "application/manifest+json",
  ".map": "application/json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".wasm": "application/wasm",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".ttf": "font/ttf",
  ".otf": "font/otf",
};

const FAVICON_SVG =
  '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">' +
  '<rect width="16" height="16" fill="#0b1020"/>' +
  '<circle cx="8" cy="8" r="5" fill="none" stroke="#7df9ff" stroke-width="1.5"/>' +
  '<circle cx="8" cy="8" r="1.5" fill="#7df9ff"/>' +
  "</svg>";

function contentTypeFor(file) {
  return CONTENT_TYPES[path.extname(file).toLowerCase()] || "application/octet-stream";
}

function tryRead(file) {
  try {
    return fs.readFileSync(file);
  } catch {
    return null;
  }
}

// First readable body across the staged-to-workspace fallback chain.
function tryReadFirst(...files) {
  for (const file of files) {
    const body = tryRead(file);
    if (body !== null) {
      return body;
    }
  }
  return null;
}

function send(req, res, status, contentType, body) {
  const buf = Buffer.isBuffer(body) ? body : Buffer.from(body);
  res.writeHead(status, {
    "content-type": contentType,
    "content-length": buf.length,
  });
  res.end(req.method === "HEAD" ? undefined : buf);
}

const server = http.createServer((req, res) => {
  const url = new URL(req.url || "/", "http://localhost");
  const readable = req.method === "GET" || req.method === "HEAD";
  if (readable && (url.pathname === "/health" || url.pathname === "/api/health")) {
    send(req, res, 200, "application/json", '{"ok":true,"status":"ok","rooms":0}');
    return;
  }
  if (readable && url.pathname === "/healthz") {
    send(req, res, 200, "application/json", '{"ok":true}');
    return;
  }
  if (readable && url.pathname === "/favicon.ico") {
    send(req, res, 200, "image/svg+xml", FAVICON_SVG);
    return;
  }
  if (readable && (url.pathname === "/" || url.pathname === "/index.html")) {
    // Prefer the staged root bundle; fall back to the workspace build,
    // then to the client source page when `dist/` is absent entirely.
    const built = tryReadFirst(
      path.join(ROOT_DIST, "index.html"),
      path.join(DIST, "index.html"),
    );
    if (built !== null) {
      send(req, res, 200, "text/html; charset=utf-8", built);
      return;
    }
    try {
      send(req, res, 200, "text/html; charset=utf-8", fs.readFileSync(INDEX));
    } catch (err) {
      send(req, res, 500, "text/plain; charset=utf-8", "failed to read index.html");
    }
    return;
  }
  if (readable && url.pathname === "/main.js") {
    const built = tryReadFirst(path.join(ROOT_DIST, "main.js"), path.join(DIST, "main.js"));
    if (built !== null) {
      send(req, res, 200, "text/javascript; charset=utf-8", built);
      return;
    }
    try {
      send(req, res, 200, "text/javascript; charset=utf-8", fs.readFileSync(MAIN));
    } catch (err) {
      send(req, res, 500, "text/plain; charset=utf-8", "failed to read main.ts");
    }
    return;
  }
  if (readable && url.pathname === "/sw.js") {
    // Offline-first worker (issue #159): staged-first chain like /main.js,
    // falling back to the public/ source so dev-without-build answers 200.
    const built = tryReadFirst(
      path.join(ROOT_DIST, "sw.js"),
      path.join(DIST, "sw.js"),
      path.join(ROOT, "packages", "client", "public", "sw.js"),
    );
    if (built !== null) {
      send(req, res, 200, "text/javascript; charset=utf-8", built);
      return;
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname === "/manifest.webmanifest") {
    // PWA manifest (issue #159): same staged-first fallback chain.
    const built = tryReadFirst(
      path.join(ROOT_DIST, "manifest.webmanifest"),
      path.join(DIST, "manifest.webmanifest"),
      path.join(ROOT, "packages", "client", "public", "manifest.webmanifest"),
    );
    if (built !== null) {
      send(req, res, 200, "application/manifest+json", built);
      return;
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname === "/tokens.css") {
    // Design tokens (issue #311): same staged-first fallback chain.
    const built = tryReadFirst(
      path.join(ROOT_DIST, "tokens.css"),
      path.join(DIST, "tokens.css"),
      path.join(ROOT, "packages", "client", "public", "tokens.css"),
    );
    if (built !== null) {
      send(req, res, 200, "text/css; charset=utf-8", built);
      return;
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname === "/layers.css") {
    // Layer discipline (issue #313): same staged-first fallback chain.
    const built = tryReadFirst(
      path.join(ROOT_DIST, "layers.css"),
      path.join(DIST, "layers.css"),
      path.join(ROOT, "packages", "client", "public", "layers.css"),
    );
    if (built !== null) {
      send(req, res, 200, "text/css; charset=utf-8", built);
      return;
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname === "/menu.css") {
    // Menu layout hierarchy (issue #314): same staged-first fallback chain.
    const built = tryReadFirst(
      path.join(ROOT_DIST, "menu.css"),
      path.join(DIST, "menu.css"),
      path.join(ROOT, "packages", "client", "public", "menu.css"),
    );
    if (built !== null) {
      send(req, res, 200, "text/css; charset=utf-8", built);
      return;
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname === "/hud.css") {
    // Cohesive HUD modules (issue #317): same staged-first fallback chain.
    const built = tryReadFirst(
      path.join(ROOT_DIST, "hud.css"),
      path.join(DIST, "hud.css"),
      path.join(ROOT, "packages", "client", "public", "hud.css"),
    );
    if (built !== null) {
      send(req, res, 200, "text/css; charset=utf-8", built);
      return;
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname.startsWith("/components/")) {
    // Panel/button primitives (issue #312): same staged-first chain as
    // /tokens.css, plus the public/ source so dev-without-build answers.
    const rel = path.normalize(url.pathname.slice("/components/".length));
    const dirs = [
      path.join(ROOT_DIST, "components"),
      path.join(DIST, "components"),
      path.join(ROOT, "packages", "client", "public", "components"),
    ];
    for (const componentsBase of dirs) {
      const file = path.join(componentsBase, rel);
      if (file !== componentsBase && !file.startsWith(componentsBase + path.sep)) {
        send(req, res, 404, "text/plain; charset=utf-8", "not found");
        return;
      }
      const body = tryRead(file);
      if (body !== null) {
        send(req, res, 200, contentTypeFor(file), body);
        return;
      }
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname.startsWith("/overlays/")) {
    // Panel overlays (issue #319): same staged-first chain as
    // /components/*, plus the public/ source so dev-without-build answers.
    const rel = path.normalize(url.pathname.slice("/overlays/".length));
    const dirs = [
      path.join(ROOT_DIST, "overlays"),
      path.join(DIST, "overlays"),
      path.join(ROOT, "packages", "client", "public", "overlays"),
    ];
    for (const overlaysBase of dirs) {
      const file = path.join(overlaysBase, rel);
      if (file !== overlaysBase && !file.startsWith(overlaysBase + path.sep)) {
        send(req, res, 404, "text/plain; charset=utf-8", "not found");
        return;
      }
      const body = tryRead(file);
      if (body !== null) {
        send(req, res, 200, contentTypeFor(file), body);
        return;
      }
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname.startsWith("/assets/")) {
    const rel = path.normalize(url.pathname.slice("/assets/".length));
    // Same staged-first chain as the page/bundle routes above.
    for (const base of [ROOT_DIST, DIST]) {
      const assetsBase = path.join(base, "assets");
      const file = path.join(assetsBase, rel);
      if (file !== assetsBase && !file.startsWith(assetsBase + path.sep)) {
        send(req, res, 404, "text/plain; charset=utf-8", "not found");
        return;
      }
      const body = tryRead(file);
      if (body !== null) {
        send(req, res, 200, contentTypeFor(file), body);
        return;
      }
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  if (readable && url.pathname.startsWith("/icons/")) {
    const rel = path.normalize(url.pathname.slice("/icons/".length));
    // Same staged-first chain as /assets/*, plus the public/ source so
    // dev-without-build resolves the manifest icon (issue #159).
    const dirs = [
      path.join(ROOT_DIST, "icons"),
      path.join(DIST, "icons"),
      path.join(ROOT, "packages", "client", "public", "icons"),
    ];
    for (const iconsBase of dirs) {
      const file = path.join(iconsBase, rel);
      if (file !== iconsBase && !file.startsWith(iconsBase + path.sep)) {
        send(req, res, 404, "text/plain; charset=utf-8", "not found");
        return;
      }
      const body = tryRead(file);
      if (body !== null) {
        send(req, res, 200, contentTypeFor(file), body);
        return;
      }
    }
    send(req, res, 404, "text/plain; charset=utf-8", "not found");
    return;
  }
  send(req, res, 404, "text/plain; charset=utf-8", "not found");
});

function onReady() {
  const addr = server.address();
  const port = typeof addr === "object" && addr !== null ? addr.port : PORT;
  const host = typeof addr === "object" && addr !== null ? addr.address : "?";
  console.log(`scrapline listening on http://localhost:${port} (bound ${host}:${port})`);
}

let fallbackTried = false;
server.on("error", (err) => {
  const code = err && err.code ? err.code : "UNKNOWN";
  if (
    !fallbackTried &&
    (code === "EADDRNOTAVAIL" || code === "EAFNOSUPPORT" || code === "ENOTSUP")
  ) {
    // Kernels without IPv6 reject the dual-stack wildcard: retry IPv4-only.
    fallbackTried = true;
    console.error(`scrapline: dual-stack listen failed (${code}), retrying on 0.0.0.0:${PORT}`);
    server.listen({ port: PORT, host: "0.0.0.0" }, onReady);
    return;
  }
  console.error(`scrapline: listen error on port ${PORT} host=${fallbackTried ? "0.0.0.0" : "::"} code=${code}: ${err && err.message ? err.message : err}`);
  process.exit(1);
});

// NOTE: binding intentionally ignores any --host/HOST argument and always
// opens a dual-stack wildcard socket: the harness probes 127.0.0.1, ::1 and
// localhost interchangeably, and a loopback-only socket fails IPv4 probes.
// A bare server.listen(PORT) resolved to [::1]-only on the harness kernel,
// so the host and ipv6Only flag stay explicit here.
server.listen({ port: PORT, host: "::", ipv6Only: false }, onReady);
